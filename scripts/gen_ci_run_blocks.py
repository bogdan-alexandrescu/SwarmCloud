#!/usr/bin/env python3
"""Publish the shell of every CI `run:` block as JSON, for the tests that execute it.

    uv run python scripts/gen_ci_run_blocks.py           # (re)write the file
    uv run python scripts/gen_ci_run_blocks.py --check   # exit 1 if it is stale
    uv run python scripts/gen_ci_run_blocks.py --inputs  # the files it reads

WHY (issue 71). Unit tests read only their own tree: a test under tests/ never
opens a file under .github/. But some workflow steps are programs -- the
auto-merge gate, the merge train's tick, ready-on-green's judge -- and their
tests RUN that shell against a fake `gh` or `git`. That text is a value that
really crosses trees, so its owner, the CI tree, publishes it here and the
tests read the published copy through tests/unit/scripts/ci_run_blocks.py
(`run_block(workflow, job, step)`). Nothing else of a workflow is published:
no triggers, permissions, `if`, `needs`, `uses`, action pins, `env` or
`shell`, so no test can pin a workflow's structure through this file.

THE SOURCES. Every `.github/workflows/*.yml` and every composite action's
`.github/actions/*/action.yml` (INPUTS), parsed with PyYAML.

THE OUTPUT. `scripts/generated/ci-run-blocks.json`, deterministic: sorted
keys, two-space indent, a trailing newline, and a `"` that follows `=` inside
a string written as its unicode escape, backslash-u-0022 (see `render`). Its
fields and their consumers:

* `files` -- one entry per source, keyed by its repository-relative path.
  Consumer: `ci_run_blocks.run_block`, which resolves a workflow's basename
  (`"auto-merge.yml"`) or a path to the entry.
* `files.<workflow>.jobs.<job id>.steps.<step key>.run` -- a workflow step's
  `run:` text exactly as YAML reads it. Consumer: `run_block`, called by
  the tests under tests/unit/scripts/ that execute the step.
* `files.<action>.steps.<step key>.run` -- the same for a composite action,
  whose steps sit under `runs.steps` and belong to no job. Consumer:
  `run_block(action, None, step)`.
* `//` -- the one line saying the file is generated and how to regenerate it.
  Consumer: whoever opens the file.

A STEP'S KEY is its `id`, else its `name`, else `step-<n>` (its 1-based
position among the job's steps); a key a job already used gets ` (2)`,
` (3)`, ... in step order. A job or action with no `run` step is left out.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import yaml

REPO = Path(__file__).resolve().parents[1]
OUTPUT_RELATIVE = "scripts/generated/ci-run-blocks.json"
REGENERATE = "uv run python scripts/gen_ci_run_blocks.py"

#: What the output is a function of, repository-relative globs; `--inputs`
#: prints the files they match, then this script and the output.
SOURCE_GLOBS = (".github/workflows/*.yml", ".github/actions/*/action.yml")


def sources(root: Path) -> list[Path]:
    """Every workflow and composite action under `root`, sorted by path."""
    found: set[Path] = set()
    for pattern in SOURCE_GLOBS:
        found.update(path for path in root.glob(pattern) if path.is_file())
    return sorted(found, key=lambda path: path.relative_to(root).as_posix())


def _steps(steps: Any) -> dict[str, dict[str, str]]:
    """The `run` text of every step that has one, by its key (see above)."""
    published: dict[str, dict[str, str]] = {}
    for position, step in enumerate(steps or [], start=1):
        if not isinstance(step, dict) or not isinstance(step.get("run"), str):
            continue
        base = str(step.get("id") or step.get("name") or f"step-{position}")
        key, count = base, 1
        while key in published:
            count += 1
            key = f"{base} ({count})"
        published[key] = {"run": step["run"]}
    return published


def blocks(path: Path) -> dict[str, Any] | None:
    """One source's published entry, or None when it holds no run block."""
    data = yaml.safe_load(path.read_text())
    if not isinstance(data, dict):
        return None
    if isinstance(data.get("jobs"), dict):
        jobs = {}
        for job_id, job in data["jobs"].items():
            steps = _steps(job.get("steps") if isinstance(job, dict) else None)
            if steps:
                jobs[str(job_id)] = {"steps": steps}
        return {"jobs": jobs} if jobs else None
    runs = data.get("runs")
    if isinstance(runs, dict):
        steps = _steps(runs.get("steps"))
        return {"steps": steps} if steps else None
    return None


def render(root: Path) -> str:
    files = {}
    for path in sources(root):
        entry = blocks(path)
        if entry is not None:
            files[path.relative_to(root).as_posix()] = entry
    document = {
        "//": f"GENERATED by scripts/gen_ci_run_blocks.py from .github/ -- do not edit; regenerate: {REGENERATE}",
        "files": files,
    }
    text = json.dumps(document, indent=2, sort_keys=True, ensure_ascii=False) + "\n"
    # A quote right after `=` is written `\u0022`, the same JSON string: the
    # worker's publish scan reads the plain escape in `GH_TOKEN=\"${APP_TOKEN}\"`
    # as a literal credential assigned to a name, and refuses the diff. `=` is
    # never part of an escape, so `=\"` occurs only as an escaped quote.
    return text.replace('=\\"', "=\\u0022")


def main(argv: list[str] | None = None, root: Path = REPO) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true",
                      help="write nothing; exit 1 if the committed file is stale")
    mode.add_argument("--inputs", action="store_true",
                      help="print the files the output is a function of, one a line, and build nothing")
    args = parser.parse_args(argv)
    output = root / OUTPUT_RELATIVE
    if args.inputs:
        names = [path.relative_to(root).as_posix() for path in sources(root)]
        print("\n".join([*names, "scripts/gen_ci_run_blocks.py", OUTPUT_RELATIVE]))
        return 0
    text = render(root)
    if args.check:
        current = output.read_text() if output.is_file() else ""
        if current != text:
            print(f"{OUTPUT_RELATIVE} is stale; regenerate it: {REGENERATE}", file=sys.stderr)
            return 1
        print(f"{OUTPUT_RELATIVE} is current")
        return 0
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text)
    print(f"wrote {OUTPUT_RELATIVE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
